def chapter(n: int) -> Chapter:
    return CHAPTERS[n - 1]


def in_chapter(n: int) -> list[Level]:
    return [lv for lv in LEVELS if lv.chapter == n]


def next_level(key: str) -> Level | None:
    keys = [lv.key for lv in LEVELS]
    if key not in keys:
        return None
    i = keys.index(key) + 1
    return LEVELS[i] if i < len(LEVELS) else None


def goal_words(lv: Level) -> str:
    if lv.endless:
        return "Survive as long as you can"
    return {
        "survive": f"Survive {lv.target} seconds",
        "clear": f"Put down {lv.target}",
        "escape": f"Find {lv.target} fuel cans, then get out",
        "defend": f"Keep the generator running for {lv.target} seconds",
        "boss": "Bring down the big one" if lv.target == 1 else f"Bring down all {lv.target} big ones",
    }[lv.goal]
