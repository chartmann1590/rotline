"""Rotline's levels: three chapters of four, and the endless mode. Data only, no GTK.

Map legend (one character a tile):

    #  wall          c  car          t  tree        x  crates      ~  water      f  fence (shots pass)
    .  ground        ,  road         =  floor indoors
    P  start         S  where the dead come from
    E  the way out   F  a fuel can   G  the generator
    h  medkit        a  ammo

Goals: survive (seconds), clear (kills), escape (fuel cans, then the way out), defend (keep the generator
running for the seconds) and boss (put the big ones down).
"""
from __future__ import annotations

from dataclasses import dataclass, field

FREE_CHAPTER = 1
CHAPTER_PRODUCTS = {2: "rotline_chapter2", 3: "rotline_chapter3"}


@dataclass(frozen=True)
class Chapter:
    number: int
    name: str
    blurb: str
    theme: str          # suburb, downtown, harbor: colours and the light


@dataclass(frozen=True)
class Level:
    key: str
    chapter: int
    name: str
    brief: str
    goal: str           # survive, clear, escape, defend, boss
    target: int         # seconds, kills, or bosses
    rate: tuple         # zombies a second: at the start, after the ramp
    ramp: int           # seconds to reach the second rate
    max_alive: int
    mix: tuple          # (kind, weight, from second)
    map: str
    unlocks: str = ""   # the weapon you find when you finish it
    bosses: int = 0
    gen_hp: int = 400
    endless: bool = False
    tips: tuple = field(default_factory=tuple)

    @property
    def rows(self) -> list[str]:
        lines = [ln.rstrip() for ln in self.map.strip("\n").splitlines()]
        width = max(len(ln) for ln in lines)
        out = []
        for ln in lines:
            short = width - len(ln)
            if short and ln.endswith("#") and set(ln) != {"#"}:
                fill = ln[-2] if ln[-2] in ".,=~" else "."
                ln = ln[:-1] + fill * short + "#"
            out.append(ln.ljust(width, "#"))
        return out

    @property
    def number(self) -> str:
        return self.key


